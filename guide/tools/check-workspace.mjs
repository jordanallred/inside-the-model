import assert from 'node:assert/strict';
import '../public/js/itm-weights.js';
import '../public/js/itm-model.js';
import '../public/js/case-engine.js';
import '../public/js/case-catalog.js';
await import('../public/js/case-workspace.js');
const W=globalThis.ITMWorkspace,C=globalThis.ITMCases;
assert.ok(W,'open experiments have a workspace distinct from graded legacy progress');
const map=new Map(),storage={getItem:k=>map.get(k)||null,setItem:(k,v)=>map.set(k,v)};
const first=W.load(storage),stale=W.load(storage);
let a=W.commit(storage,first,'confidence',{prompt:'the dog chased the',temperature:.5,explored:true});
let b=W.commit(storage,stale,'confidence',{temperature:3});
assert.equal(b.state.cases.confidence.prompt,'the dog chased the');
assert.equal(b.state.cases.confidence.explored,true);
assert.equal(b.state.cases.confidence.temperature,3);
assert.equal(b.persisted,true);
const reset=W.reset(storage,b.state,'confidence');
assert.equal(reset.state.cases.confidence.explored,true,'resetting inputs does not delete exploration history');
assert.equal(reset.state.cases.confidence.temperature,2);
const broken={getItem(){throw Error('blocked');},setItem(){throw Error('blocked');}};
const local=W.commit(broken,W.load(broken),'place',{head:1,explored:true});
assert.equal(local.persisted,false);assert.equal(local.state.cases.place.head,1);
map.delete(W.KEY);map.set('itm-investigations-v2',JSON.stringify({version:2,cases:{place:{prediction:'changes',experiment:1,completed:true,seen:[0]}}}));
const legacy=W.load(storage);assert.equal(legacy.cases.place.explored,true);assert.equal(legacy.cases.place.head,1);
W.commit(storage,legacy,'training',{explored:true});
assert.deepEqual(JSON.parse(map.get('itm-investigations-v2')).cases.place.seen,[0],'legacy data is left intact');
assert.equal(W.normalize({version:1,cases:{confidence:{temperature:0,prompt:'alien spaceship'}}}).cases.confidence.temperature,2);
console.log('Open workspaces preserve input state, legacy history, cross-tab changes and blocked-storage sessions.');
const finished=C.normalizeProgress({version:2,cases:{place:{prediction:'changes',experiment:1,design:'diagnostic',explanation:'verb',transfer:'place'}}});
assert.equal(C.transition(finished,'place','transfer','animal').cases.place.completed,true,'legacy completed records cannot be undone by a stale transfer form');
const baselineIds=globalThis.ITM.tokenize('the cat sat on the').ids;
for(const p of C.runControl('diagnostic').probes){const ids=globalThis.ITM.tokenize(p.prompt).ids;assert.equal(ids.length,baselineIds.length,'clean controls preserve token positions');assert.equal(ids.filter((v,i)=>v!==baselineIds[i]).length,1);}
assert.throws(()=>C.runFuture('the cat sat on the mat','the cat sat on the mat',3),/different|change/i,'repeating identical inputs is not a suffix intervention');
